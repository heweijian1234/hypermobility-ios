import SwiftUI
import MessageUI

// 带附件的邮件直发（发给医生场景）
struct PDFMailComposer: UIViewControllerRepresentable {
    let attachment: Data
    let filename: String

    func makeUIViewController(context: Context) -> MFMailComposeViewController {
        let m = MFMailComposeViewController()
        m.setSubject("HyperLog Joint Report")
        m.setMessageBody("Hi doctor, attached is my joint episode report (generated by HyperLog).", isHTML: false)
        m.addAttachmentData(attachment, mimeType: "application/pdf", fileName: filename)
        m.mailComposeDelegate = context.coordinator
        return m
    }
    func updateUIViewController(_ vc: MFMailComposeViewController, context: Context) {}
    func makeCoordinator() -> Coordinator { Coordinator() }
    final class Coordinator: NSObject, MFMailComposeViewControllerDelegate {
        func mailComposeController(_ controller: MFMailComposeViewController, didFinishWith result: MFMailComposeResult, error: Error?) {
            controller.dismiss(animated: true)
        }
    }
}
